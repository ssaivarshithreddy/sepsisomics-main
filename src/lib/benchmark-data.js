export function cohortToCsv(cohort) {
  if (!cohort || cohort.length === 0) return "";
  const keys = Object.keys(cohort[0]).filter((k) => k !== "label");
  const headerLine = keys.join(",");
  const rows = cohort.map((patient) => keys.map((k) => patient[k] ?? "").join(","));
  return [headerLine, ...rows].join("\n");
}
